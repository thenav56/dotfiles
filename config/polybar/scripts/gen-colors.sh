#!/usr/bin/env bash
# Generate polybar colors from a base16-shell scheme script.
#
# Usage: gen-colors.sh [scheme-script]   (default: ~/.base16_theme symlink)
# Light schemes are swapped for a dark counterpart -- the bar is always dark.
#
# Writes:
#   ~/.config/polybar/colors.ini  [base16] section, included by polybar-base.ini
#   ~/.config/polybar/colors.sh   shell vars for scripts that print %{F#..} tags

set -euo pipefail

SCHEME="${1:-$HOME/.base16_theme}"
OUT_DIR="$HOME/.config/polybar"
SCRIPTS="$HOME/.dotfiles/base16/shell/scripts"
FALLBACK="$SCRIPTS/base16-tomorrow-night.sh"

[ -f "$SCHEME" ] || SCHEME="$FALLBACK"
SCHEME=$(readlink -f "$SCHEME")
mkdir -p "$OUT_DIR"

# Scheme lines look like: color01="cc/66/66" # Base 08 - Red
parse() {
    sed -nE 's|^color[0-9]+="([0-9a-fA-F]{2})/([0-9a-fA-F]{2})/([0-9a-fA-F]{2})" # Base (0[0-9A-F]).*|base\4 = #\1\2\3|p' "$1"
}
base() { echo "$COLORS" | sed -n "s/^$1 = //p"; }
is_light() {
    local bg=$(base base00)
    [ $(( (299 * 16#${bg:1:2} + 587 * 16#${bg:3:2} + 114 * 16#${bg:5:2}) / 1000 )) -gt 128 ]
}

COLORS=$(parse "$SCHEME")

# The bar stays dark and day matches night: for a light scheme, use the zshrc
# night theme, else the last dark scheme seen here (i3's launch has no zshrc
# env), else the same family's dark variant (gruvbox-light-hard ->
# gruvbox-dark-hard, one-light -> onedark), else tomorrow-night.
LAST_DARK="$OUT_DIR/last-dark-scheme"
if is_light; then
    name=$(basename "$SCHEME")
    night=""
    [ -n "${BASE16_NIGHT_THEME:-}" ] && night="$SCRIPTS/${BASE16_NIGHT_THEME/base16_/base16-}.sh"
    last=""
    [ -f "$LAST_DARK" ] && last=$(cat "$LAST_DARK")
    for candidate in "$night" "$last" "$SCRIPTS/${name/light/dark}" "$SCRIPTS/${name/-light/}" \
                     "$SCRIPTS/${name/-light/dark}" "$FALLBACK"; do
        if [ -f "$candidate" ] && [ "$(readlink -f "$candidate")" != "$SCHEME" ]; then
            SCHEME=$(readlink -f "$candidate")
            COLORS=$(parse "$SCHEME")
            is_light || break
        fi
    done
else
    echo "$SCHEME" > "$LAST_DARK"
fi

if [ "$(echo "$COLORS" | wc -l)" -ne 16 ]; then
    echo "gen-colors: could not parse 16 base colors from $SCHEME" >&2
    exit 1
fi

# mix <fg> <bg> <pct-of-fg> -> #rrggbb
mix() {
    local out="#" i
    for i in 1 3 5; do
        out+=$(printf '%02x' $(( (16#${1:$i:2} * $3 + 16#${2:$i:2} * (100 - $3)) / 100 )))
    done
    echo "$out"
}

# Dim text: base04/base03 are too dark in some schemes (onedark's base04 is
# ~bg), so derive them from the text color instead.
FG_DIM=$(mix "$(base base05)" "$(base base00)" 80)
FG_DISABLED=$(mix "$(base base05)" "$(base base00)" 55)

# Translucent bar (macOS-style): base00 tinted over picom's blur of the
# wallpaper (picom.conf blurs docks only). Alpha is #AARRGGBB's AA.
BAR_BG="#B3$(base base00 | cut -c2-)"       # 70%
BAR_SEL="#CC$(base base02 | cut -c2-)"      # 80%

{
    echo "; Generated by config/polybar/scripts/gen-colors.sh from $(basename "$SCHEME")"
    echo "[base16]"
    echo "$COLORS" | sort
    echo
    echo "[theme]"
    echo "background = $BAR_BG"
    echo "selection = $BAR_SEL"
    echo "foreground-dim = $FG_DIM"
    echo "disabled = $FG_DISABLED"
} > "$OUT_DIR/colors.ini"

{
    echo "# Generated by config/polybar/scripts/gen-colors.sh"
    echo "$COLORS" | sed -E 's/^(base0[0-9A-F]) = (.*)/POLYBAR_\1="\2"/'
} > "$OUT_DIR/colors.sh"
